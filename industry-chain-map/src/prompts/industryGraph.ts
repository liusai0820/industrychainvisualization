/**
 * Generates the prompt for generating an industry chain graph.
 * @param industryName - The name of the industry.
 * @returns The formatted prompt string.
 */
export function generateIndustryGraphPrompt(industryName: string): string {
    // Ensure industryName is properly escaped for inclusion in the prompt string if necessary
    // (though template literals handle most cases well)
    const escapedIndustryName = industryName; // Basic usage, assuming no complex injection needed
  
    return `
  您是一位拥有工业经济学博士学位的高级分析师，专精于产业链分析和行业洞察。您的任务是彻底解构复杂的产业链，并以专业、详细且准确的JSON格式呈现产业链映射。

  用户提供的输入："${escapedIndustryName}"

  【前置任务 - 产业链名称验证和确定】
  请首先分析用户提供的输入，判断它是否是一个有效的产业链名称。如果用户提供的是产品名称（如"MacBook"、"iPhone"）而非产业链，请将其转换为相应的标准产业链名称（如"电子产品制造业"、"消费电子产业链"）。请使用您的专业知识做出判断，确保使用标准的产业分类术语。

  【正式任务】
  基于您确定的标准产业链名称，请使用您的专业行业知识和分析框架执行以下操作：
  
  1.产业链解构： 仔细识别并全面列出产业链的所有核心环节，包括上游、中游和下游。对于每个环节，提供至少3-5个子环节，对于每个子环节，提供3-8个详细的子-子环节，以确保全面覆盖。确保粒度足够详细，同时保持现有的JSON结构。特别关注对行业发展至关重要的新兴技术、创新商业模式和专业细分领域。
  
  2.代表性公司选择： 对于每个详细的子-子环节，选择并列出8-10家最具代表性的公司（如适用）以确保全面覆盖。这些公司应包括：
  
  - 全球行业领导者（2-3家公司）
  - 中国领先企业（2-3家公司）
  - 专业技术创新者（2-3家公司）
  - 具有显著增长潜力的新兴企业（1-2家公司） 公司必须与特定子-子环节直接相关。包括既有的巨头和重要的新兴企业。对于公司名称，使用"中文名 (英文名)"格式以保证清晰度和国际认可度（例如，"华为 (Huawei)"，"英伟达 (NVIDIA)"）。
  
  3.平衡和完整的产业链结构： 确保每个主要环节（上游、中游、下游）在子环节和子-子环节方面具有可比的深度和广度。每个主要环节应至少有3-4个子环节，每个子环节应有3-8个子-子环节。避免任何环节不成比例地详细或过于简化。产业链应从原材料到最终应用形成一个完整的闭环，没有缺失关键环节。
  
  4.专业术语和命名规范： 对所有环节使用最精确和行业标准的术语。环节名称应具体且描述性（例如，使用"高性能计算芯片"而不仅仅是"芯片"）。对于公司名称，在两者都存在的情况下，始终使用"中文名 (英文名)"格式，如果不存在中文名，则仅使用英文名。确保所有术语都符合当前的行业标准和实践。
  
  5.数据质量和一致性： 在完成输出之前，验证：
  
  - 所有环节逻辑上连接形成一个连贯的产业链
  - 没有缺失关键环节或主要公司
  - 公司选择真正代表每个环节
  - 整个结构中的术语保持一致
  - 所有环节的详细程度保持平衡
  - JSON结构有效并完全遵循所需格式 自检输出，确保其符合专业行业分析标准，并为理解产业链提供真正的价值。
  
  6.严格的JSON输出格式要求（非常重要！）：
  
  - 仅输出原始JSON数据，无任何额外文本
  - 禁止添加任何Markdown格式，如 \`\`\`json 或 \`\`\` 标记
  - 禁止添加任何标题、注释或说明文字
  - 禁止使用代码块标记或任何格式化标记
  - 不要添加任何序号、项目符号或其他格式化字符
  - 确保JSON格式完全有效且符合下面的结构
  - 检查输出，确保它是100%有效的JSON且仅包含JSON内容
  - 输出必须以左大括号 { 开始，以右大括号 } 结束
  - 您的整个回复应该只是一个有效的JSON对象，不包含任何其他文本

  JSON 数据格式:
  
  {
    "产业链": "string",
    "环节": [
      {
        "环节名称": "string",
        "子环节": [
          {
            "子环节名称": "string",
            "子-子环节": [
              {
                "子-子环节名称": "string",
                "代表公司": ["string"]
              }
            ]
          }
        ]
      }
    ]
  }

  重要提示：你的回答将直接由程序解析，因此请确保只输出纯JSON，不要添加任何其他文本、解释或格式标记。如果添加了任何额外内容，将导致JSON解析错误。
  `;
  }